/** Row label without the trailing colon, in the requested language. */
export function physicalExamRowLabel(
  section: 'ros' | 'exam',
  key: string,
  englishLabel: string,
  language: PhysicalExamLanguage
): string {
  if (language !== 'es') return englishLabel
  return (section === 'ros' ? ES_ROS_LABELS : ES_EXAM_LABELS)[key] ?? englishLabel
}

export function physicalExamExtraLabel(key: string, englishLabel: string, language: PhysicalExamLanguage): string {
  return language === 'es' ? ES_EXTRA_LABELS[key] ?? englishLabel : englishLabel
}

/** Display text for a finding chip; the stored value stays the English label. */
export function physicalExamFindingLabel(label: string, language: PhysicalExamLanguage): string {
  return language === 'es' ? ES_FINDINGS[label.trim().toLowerCase()] ?? label : label
}
